#!/usr/bin/env bash
# Generates or checks third_party/go-licenses/GO-LICENSES.txt: the verbatim
# licence and notice files of the Go code statically linked into
# /usr/bin/gswitch and /usr/bin/gswitch-tray besides gswitch-auto itself
# (LICENSE) and the vendored golang.design/x/clipboard
# (third_party/clipboard/LICENSE): the Go runtime and standard library and
# every module `go list -deps` reports for ./cmd/gswitch and
# ./cmd/gswitch-tray. Their BSD, ISC and Apache-2.0 licences require the
# notices to accompany binary redistribution; both packages ship the file
# (packaging/nfpm.yaml) and packaging/debian/copyright refers to it; every
# linked module must also have a "go-modules/<path>/*" paragraph there.
#
# Usage: scripts/go-licenses.sh [--check | --write]
#   --check  (default) regenerate into a temporary file and fail when it
#            differs from the committed file (a dependency or its version
#            changed: run --write and review the diff)
#   --write  regenerate the committed file
#
# Needs the Go toolchain and the module cache of go.mod (go list downloads
# missing modules). The Go toolchain's own LICENSE and PATENTS are those of
# golang.org/x/sys; when $(go env GOROOT)/LICENSE exists it is compared.
set -euo pipefail

repo_root=$(cd "$(dirname "$0")/.." && pwd)
readonly repo_root
readonly target=third_party/go-licenses/GO-LICENSES.txt
readonly go_license_module=golang.org/x/sys

mode=check
case ${1:-} in
    "" | --check) mode=check ;;
    --write) mode=write ;;
    -h | --help)
        sed -n '2,/^set -euo/p' "$0" | sed '$d; s/^# \{0,1\}//'
        exit 0
        ;;
    *)
        printf 'go-licenses: unknown argument %s\n' "$1" >&2
        exit 2
        ;;
esac

cd "$repo_root"
command -v go >/dev/null 2>&1 || {
    printf 'go-licenses: go not found\n' >&2
    exit 1
}

# modules: "path version dir" of every linked module except the main module
# and replaced (vendored) ones, sorted by path.
modules=$(go list -deps -f '{{with .Module}}{{if and (not .Main) (not .Replace)}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' \
    ./cmd/gswitch ./cmd/gswitch-tray | sort -u)
[[ -n $modules ]] || {
    printf 'go-licenses: go list reported no modules\n' >&2
    exit 1
}

# notice_files DIR: the licence and notice files at the root of DIR.
notice_files() {
    find "$1" -maxdepth 1 -type f \( -iname 'LICEN[CS]E*' -o -iname 'COPYING*' -o -iname 'NOTICE*' \
        -o -iname 'PATENTS*' -o -iname 'AUTHORS*' \) -printf '%f\n' | LC_ALL=C sort
}

rule='========================================================================'
sub='------------------------------------------------------------------------'

generate() {
    local path version dir f found go_dir=""
    printf '%s\n' \
        'Licences of the Go code statically linked into /usr/bin/gswitch and' \
        '/usr/bin/gswitch-tray, besides gswitch-auto itself (LICENSE) and the' \
        'vendored golang.design/x/clipboard (clipboard-LICENSE).' \
        '' \
        'The Go runtime and standard library are distributed under the same' \
        "LICENSE and PATENTS as $go_license_module (Copyright 2009 The Go Authors)," \
        'reproduced in its section below.' \
        '' \
        'Generated by scripts/go-licenses.sh from the module cache at the versions' \
        'of go.mod; do not edit.'
    while read -r path version dir; do
        [[ $path == "$go_license_module" ]] && go_dir=$dir
        printf '\n%s\n%s %s\n' "$rule" "$path" "$version"
        found=0
        while IFS= read -r f; do
            [[ -n $f ]] || continue
            found=1
            printf '%s %s\n' "$sub" "$f"
            cat -- "$dir/$f"
            # Keep the separator on its own line even without a final newline.
            [[ -z $(tail -c 1 -- "$dir/$f") ]] || printf '\n'
        done < <(notice_files "$dir")
        if ((found == 0)); then
            printf 'go-licenses: %s %s has no licence file in %s\n' "$path" "$version" "$dir" >&2
            return 1
        fi
    done <<<"$modules"
    if [[ -z $go_dir ]]; then
        printf 'go-licenses: %s is no longer linked; the Go toolchain licence needs another source\n' "$go_license_module" >&2
        return 1
    fi
    local goroot
    goroot=$(go env GOROOT)
    for f in LICENSE PATENTS; do
        if [[ -f $goroot/$f ]] && ! cmp -s "$goroot/$f" "$go_dir/$f"; then
            printf 'go-licenses: %s/%s differs from %s/%s; ship it separately\n' "$goroot" "$f" "$go_license_module" "$f" >&2
            return 1
        fi
    done
}

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
generate >"$tmp"

# Every linked module needs its own paragraph in the Debian copyright file.
missing_paragraphs=()
while read -r path _; do
    grep -qxF -- "Files: go-modules/$path/*" packaging/debian/copyright ||
        grep -qxF -- "       go-modules/$path/*" packaging/debian/copyright ||
        missing_paragraphs+=("$path")
done <<<"$modules"
if ((${#missing_paragraphs[@]} > 0)); then
    printf 'go-licenses: packaging/debian/copyright has no "go-modules/<path>/*" paragraph for: %s\n' "${missing_paragraphs[*]}" >&2
    exit 1
fi

if [[ $mode == write ]]; then
    mkdir -p "$(dirname "$target")"
    cp -- "$tmp" "$target"
    chmod 0644 "$target"
    printf 'wrote %s (%d modules)\n' "$target" "$(grep -c . <<<"$modules")"
    exit 0
fi

if [[ ! -f $target ]]; then
    printf 'go-licenses: %s is missing; run scripts/go-licenses.sh --write\n' "$target" >&2
    exit 1
fi
if ! diff -u -- "$target" "$tmp" >&2; then
    printf 'go-licenses: %s is out of date (the linked modules changed); run scripts/go-licenses.sh --write and review the diff\n' "$target" >&2
    exit 1
fi
printf 'ok    %s matches the %d linked Go modules\n' "$target" "$(grep -c . <<<"$modules")"
